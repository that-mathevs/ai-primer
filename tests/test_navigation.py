class TestBigQuestions:
    def test_given_every_big_question_each_lesson_on_its_route_exists(self):
        from primer.curriculum import BIG_QUESTIONS

        known = {l.module for l in CURRICULUM}
        assert [m for q in BIG_QUESTIONS for m in q.route if m not in known] == []

    def test_given_the_curriculum_every_lesson_belongs_to_at_least_one_big_question(self):
        # A lesson no big question needs is either missing from the map or not pulling its weight.
        from primer.curriculum import BIG_QUESTIONS

        covered = {m for q in BIG_QUESTIONS for m in q.route}
        assert [l.module for l in CURRICULUM if l.module not in covered] == []

    def test_given_every_big_question_its_answer_has_a_spine_of_three_to_seven_points(self):
        from primer.curriculum import BIG_QUESTIONS

        assert [q.question for q in BIG_QUESTIONS if not 3 <= len(q.spine) <= 7] == []

    def test_given_the_big_questions_the_generated_page_is_current(self):
        from primer.curriculum import big_questions_page

        assert (ROOT / "docs" / "BIG_QUESTIONS.md").read_text() == big_questions_page(), "stale: run `make readme`"

    def test_given_the_big_questions_the_readme_map_is_current(self):
        from primer.curriculum import big_questions_table

        readme = (ROOT / "README.md").read_text()
        current = re.search(r"<!-- BEGIN big-questions -->\n(.*?)<!-- END big-questions -->", readme, re.S)
        assert current and current.group(1) == big_questions_table(), "stale: run `make readme`"
